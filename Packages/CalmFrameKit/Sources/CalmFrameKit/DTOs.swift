import Foundation

// MARK: - Auth

/// Request body for `POST /v1/auth/apple`.
public struct AuthRequest: Codable, Sendable {
    /// The identity token returned by Sign in with Apple (Base64-encoded JWT).
    public var identityToken: String

    public init(identityToken: String) {
        self.identityToken = identityToken
    }
}

/// Response body for `POST /v1/auth/apple`.
public struct AuthResponse: Codable, Sendable {
    /// Server-issued JWT to include in subsequent requests as `Authorization: Bearer <token>`.
    public var token: String
    /// Current credit balance (5 for new users).
    public var balance: Int

    public init(token: String, balance: Int) {
        self.token = token
        self.balance = balance
    }
}

// MARK: - Credits

/// Response body for `GET /v1/credits`.
public struct BalanceResponse: Codable, Sendable {
    /// Current credit balance. Always `Int`; floating-point is forbidden.
    public var balance: Int

    public init(balance: Int) {
        self.balance = balance
    }
}

/// Request body for `POST /v1/credits/redeem`.
public struct RedeemRequest: Codable, Sendable {
    /// The `jwsRepresentation` from a StoreKit 2 `VerificationResult<Transaction>`.
    public var signedTransaction: String

    public init(signedTransaction: String) {
        self.signedTransaction = signedTransaction
    }
}

// MARK: - Paintings

/// Request body for `POST /v1/paintings`.
///
/// Carries only the mood label, style, and locale — no audio data whatsoever.
public struct PaintingRequest: Codable, Sendable {
    public var mood: Mood
    public var style: PaintingStyle
    /// BCP 47 language tag (e.g. `"en"`, `"zh-Hans"`) used to localise the caption.
    public var locale: String

    public init(mood: Mood, style: PaintingStyle, locale: String) {
        self.mood = mood
        self.style = style
        self.locale = locale
    }
}

/// Response body for `POST /v1/paintings` and `GET /v1/paintings/latest`.
public struct PaintingResponse: Codable, Sendable {
    /// Unique identifier of the painting in the database.
    public var id: UUID
    /// Pre-signed or CDN URL pointing to the image on R2/S3.
    public var imageURL: URL
    /// Short painting title generated by Claude (1–8 words).
    public var title: String
    /// One-sentence caption; `nil` when not applicable (e.g. calm mood).
    public var caption: String?
    /// `true` when the response was served from cache and no credit was charged.
    public var fromCache: Bool
    /// Credit balance after this operation.
    public var balance: Int

    public init(
        id: UUID,
        imageURL: URL,
        title: String,
        caption: String? = nil,
        fromCache: Bool,
        balance: Int
    ) {
        self.id = id
        self.imageURL = imageURL
        self.title = title
        self.caption = caption
        self.fromCache = fromCache
        self.balance = balance
    }
}

// MARK: - Errors

/// Generic error response body returned by the server
/// (JSON: `{ "error": "...", "retryable": true }`).
public struct APIError: Codable, Sendable, LocalizedError {
    public var error: String
    /// `true` when the client may retry with exponential back-off (e.g. AI generation failure).
    public var retryable: Bool

    public init(error: String, retryable: Bool = false) {
        self.error = error
        self.retryable = retryable
    }

    public var errorDescription: String? { error }
}
